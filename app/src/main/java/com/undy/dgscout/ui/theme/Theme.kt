/**
 * Deliberately does not offer Material You dynamic color: a wallpaper-derived
 * pastel palette looks fine indoors but washes out badly in direct sunlight,
 * which is exactly when this app gets used.
 */
@Composable
fun DGScoutTheme(
    darkTheme: Boolean = isSystemInDarkTheme(),
    content: @Composable () -> Unit
) {
    val colorScheme = if (darkTheme) DarkColorScheme else LightColorScheme

    MaterialTheme(
        colorScheme = colorScheme,
        typography = Typography,
        content = content
    )
}
